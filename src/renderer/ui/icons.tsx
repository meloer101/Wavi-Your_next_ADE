// Wavi's icons (PRD v1.204, Figma 94′): every icon the renderer draws comes from here, drawn by @hugeicons/react from
// the glyphs chosen in ui/glyphs.ts, so the set is swapped in one place. Lint keeps @hugeicons/* out of every other
// file. Call sites pass `size={16} strokeWidth={1.75}` (CLAUDE.md).
import { HugeiconsIcon } from '@hugeicons/react'
import type { ComponentType, SVGProps } from 'react'
import { GLYPHS, type GlyphName } from './glyphs'

export type IconProps = Omit<SVGProps<SVGSVGElement>, 'ref'> & { size?: number; strokeWidth?: number }
/** Any icon from this module (a tool row's, a menu item's, a nav entry's). */
export type IconComponent = ComponentType<IconProps>

function icon(name: GlyphName): IconComponent {
  const glyph = GLYPHS[name]
  const Icon = (props: IconProps) => <HugeiconsIcon icon={glyph} {...props} />
  Icon.displayName = name
  return Icon
}

